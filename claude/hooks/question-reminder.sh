#!/bin/bash
# UserPromptSubmit: 質問への答え方と合意の記録を毎ターン判断の直前に注入する。AGENTS.md だけでは会話が長くなると効かない。
# 「？」の有無では判定しない。質問でも付けないことが多いため、判定は Claude に任せる。
trap 'rc=$?; echo "$(date +%FT%T) ${0##*/} exit=$rc" >>"$HOME/.claude/hook-stats.log"' EXIT
sid=$(jq -r '.session_id // empty')

echo "この発言が質問（批判・詰問の形も含む）なら: 答えを返してターンを終える。手元の情報で答えられるなら調べない。調べるのは答えに必要な読み取りだけ。編集・状態を変えるコマンド・修正の提案・「修正します」は禁止。"
[ -n "$sid" ] && echo "この発言に、以降の判断に効く取り決め・課題の合意・ユーザーによる訂正があれば、返答の前に ~/.claude/agreements/$sid.md へ「合意: … / 理由: …」で追記する。一回きりの作業指示や結果の報告は書かない。後で蒸し返されたら困るものだけ書く。"
exit 0
